"""Generate Mantle's loadable arity and primitive array boilerplate.

Writes, under mantle/src/main/java/slimeknights/mantle/data/loadable:
  record/RecordLoadable.java          interface + create/withLoader overloads
  record/RecordLoadable1..16.java     records built from 1 to 16 fields
  record/RecordWithLoader1..15.java   same, with the loader passed to the constructor
  array/<Type>ArrayLoadable.java      primitive array loadables

WHY a generator (03 escape hatch): these 40 files differ only in arity or
element type; generating keeps them consistent and reviewable in one place.
Edit this script, never the generated files. Run from the repo root:
  python -I scripts/codegen/gen_loadables.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
LOADABLE = ROOT / "mantle/src/main/java/slimeknights/mantle/data/loadable"
LETTERS = "ABCDEFGHIJKLMNOP"
MAX_FIELDS = 16
HEADER = "// GENERATED by scripts/codegen/gen_loadables.py; edit the generator, not this file.\n"
PKG_RECORD = "package slimeknights.mantle.data.loadable.record;\n"
PKG_ARRAY = "package slimeknights.mantle.data.loadable.array;\n"


def function_type(arg_types):
    """Name the functional interface for some arguments."""
    count = len(arg_types)
    args = ", ".join(arg_types)
    if count == 1:
        return f"Function<{args}, R>"
    if count == 2:
        return f"BiFunction<{args}, R>"
    return f"Function{count}<{args}, R>"


def function_import(count):
    """Import line for a functional interface arity."""
    if count == 1:
        return "import java.util.function.Function;"
    if count == 2:
        return "import java.util.function.BiFunction;"
    return f"import com.mojang.datafixers.util.Function{count};"


def sorted_imports(lines):
    """Sort imports: third party first, then java."""
    third = sorted(line for line in lines if not line.startswith("import java."))
    java = sorted(line for line in lines if line.startswith("import java."))
    blocks = [block for block in ("\n".join(third), "\n".join(java)) if block]
    return "\n\n".join(blocks) + "\n"


def record_class(count, with_loader):
    """Source of one RecordLoadableN or RecordWithLoaderN."""
    letters = LETTERS[:count]
    name = f"RecordWithLoader{count}" if with_loader else f"RecordLoadable{count}"
    arg_types = list(letters) + (["RecordLoadable<R>"] if with_loader else [])
    fields = "".join(f"  RecordField<{x}, ? super R> field{x},\n" for x in letters)
    extra_arg = ["this"] if with_loader else []
    read_json = ", ".join([f"field{x}.get(json, context)" for x in letters] + extra_arg)
    read_net = ", ".join([f"field{x}.decode(buffer, context)" for x in letters] + extra_arg)
    write_json = "".join(f"    field{x}.serialize(object, json);\n" for x in letters)
    write_net = "".join(f"    field{x}.encode(buffer, object);\n" for x in letters)
    imports = sorted_imports([
        "import com.google.gson.JsonObject;",
        "import net.minecraft.network.RegistryFriendlyByteBuf;",
        "import slimeknights.mantle.data.loadable.field.RecordField;",
        "import slimeknights.mantle.util.typed.TypedMap;",
        function_import(len(arg_types)),
    ])
    loader_doc = ", passing itself to the constructor" if with_loader else ""
    return f"""{HEADER}{PKG_RECORD}
{imports}
/** Record loadable built from {count} field{'s' if count > 1 else ''}{loader_doc}; create through {{@link RecordLoadable}} */
record {name}<{', '.join(letters)}, R>(
{fields}  {function_type(arg_types)} constructor
) implements RecordLoadable<R> {{
  @Override
  public R deserialize(JsonObject json, TypedMap context) {{
    return constructor.apply({read_json});
  }}

  @Override
  public void serialize(R object, JsonObject json) {{
{write_json}  }}

  @Override
  public R decode(RegistryFriendlyByteBuf buffer, TypedMap context) {{
    return constructor.apply({read_net});
  }}

  @Override
  public void encode(RegistryFriendlyByteBuf buffer, R object) {{
{write_net}  }}
}}
"""


def factory(count, with_loader):
    """One create or withLoader overload."""
    letters = LETTERS[:count]
    arg_types = list(letters) + (["RecordLoadable<R>"] if with_loader else [])
    params = "".join(f"    RecordField<{x}, ? super R> field{x},\n" for x in letters)
    args = ", ".join(f"field{x}" for x in letters)
    method = "withLoader" if with_loader else "create"
    target = f"RecordWithLoader{count}" if with_loader else f"RecordLoadable{count}"
    doc = (f"Creates a record loadable from {count} field{'s' if count > 1 else ''}"
           + ("; the constructor also gets the loader" if with_loader else ""))
    return f"""
  /** {doc} */
  static <{', '.join(letters)}, R> RecordLoadable<R> {method}(
{params}    {function_type(arg_types)} constructor) {{
    return new {target}<>({args}, constructor);
  }}
"""


RECORD_LOADABLE_BODY = '''
/**
 * Loadable for an object stored as a JSON object of named fields.
 * Build one with {@link #create} from record fields plus the object's constructor.
 * @param <T>  Value type
 */
@SuppressWarnings("unused")  // API
public interface RecordLoadable<T> extends Loadable<T> {
  /**
   * Reads the object from its JSON object.
   * @param context  Parse context, notably the recipe id for recipe serializers
   * @throws com.google.gson.JsonSyntaxException  If a field is invalid
   */
  T deserialize(JsonObject json, TypedMap context);

  /** Reads the object with empty context */
  default T deserialize(JsonObject json) {
    return deserialize(json, TypedMap.EMPTY);
  }

  @Override
  default T convert(JsonElement element, String key, TypedMap context) {
    return deserialize(GsonHelper.convertToJsonObject(element, key), context);
  }

  /** Writes the object's fields into an existing JSON object */
  void serialize(T object, JsonObject json);

  @Override
  default JsonElement serialize(T object) {
    JsonObject json = new JsonObject();
    serialize(object, json);
    return json;
  }


  /* Fields */

  /** Creates a field whose keys sit directly in the parent object, sharing its parse context */
  default <P> RecordField<T, P> directField(Function<P, T> getter) {
    return new DirectField<>(this, getter);
  }

  /**
   * Adds a short JSON form, read from any non-object JSON.
   * @param compact    Short form
   * @param condition  True when a value should be written in the short form
   */
  default RecordLoadable<T> compact(Loadable<T> compact, Predicate<T> condition) {
    return CompactLoadable.of(this, compact, condition);
  }


  /* Mapping keeps the record form */

  @Override
  default <M> RecordLoadable<M> mapChecked(BiFunction<T, ErrorFactory, M> constructor, BiFunction<M, ErrorFactory, T> getter) {
    return MappedLoadable.of(this, constructor, getter);
  }

  @Override
  default <M> RecordLoadable<M> map(Function<? super T, ? extends M> constructor, Function<? super M, ? extends T> getter) {
    return mapChecked(Loadable.noErrors(constructor), Loadable.noErrors(getter));
  }

  @Override
  default RecordLoadable<T> validate(BiFunction<T, ErrorFactory, T> validator) {
    return mapChecked(validator, validator);
  }


  /* Factories */

  /** Creates a record loadable with no fields, for an instance that holds its own loader */
  static <R> RecordLoadable<R> withLoader(Function<RecordLoadable<R>, R> constructor) {
    return new SingletonLoader<>(constructor);
  }
'''


def record_loadable():
    """Source of RecordLoadable.java with every overload."""
    imports = sorted_imports([
        "import com.google.gson.JsonElement;",
        "import com.google.gson.JsonObject;",
        "import net.minecraft.util.GsonHelper;",
        "import slimeknights.mantle.data.loadable.ErrorFactory;",
        "import slimeknights.mantle.data.loadable.Loadable;",
        "import slimeknights.mantle.data.loadable.field.DirectField;",
        "import slimeknights.mantle.data.loadable.field.RecordField;",
        "import slimeknights.mantle.data.loadable.mapping.CompactLoadable;",
        "import slimeknights.mantle.data.loadable.mapping.MappedLoadable;",
        "import slimeknights.mantle.util.typed.TypedMap;",
        "import java.util.function.BiFunction;",
        "import java.util.function.Function;",
        "import java.util.function.Predicate;",
    ] + [f"import com.mojang.datafixers.util.Function{n};" for n in range(3, MAX_FIELDS + 1)])
    creates = "".join(factory(n, False) for n in range(1, MAX_FIELDS + 1))
    loaders = "".join(factory(n, True) for n in range(1, MAX_FIELDS))
    return f"{HEADER}{PKG_RECORD}\n{imports}{RECORD_LOADABLE_BODY}{creates}{loaders}}}\n"


# (class prefix, primitive, boxed, read from base, write to base) for arrays whose loadable has the boxed type
DIRECT_ARRAYS = [
    ("Int", "int", "Integer"),
    ("Long", "long", "Long"),
    ("Float", "float", "Float"),
    ("Double", "double", "Double"),
    ("Boolean", "boolean", "Boolean"),
    ("Char", "char", "Character"),
]
# (class prefix, primitive) for arrays narrowed from any number loadable
NARROWED_ARRAYS = [("Short", "short"), ("Byte", "byte")]


def array_class(prefix, primitive, base_type, narrowed):
    """Source of one primitive array loadable."""
    name = f"{prefix}ArrayLoadable"
    if narrowed:
        header = (f"public record {name}<T extends Number>(Loadable<T> base, int minSize, int maxSize, IntFunction<T> mapper)"
                  f" implements ArrayLoadable.SizeRange<{primitive}[]> {{")
        read = lambda expr: f"{expr}.{primitive}Value()"
        write = lambda expr: f"mapper.apply({expr})"
        doc = f"Loadable for a {primitive} array, read through any number loadable and narrowed to {primitive}"
        mapper_doc = f"\n * @param mapper   Boxes a {primitive} for the base loadable, such as {{@code Integer::valueOf}}"
        extra_import = ["import java.util.function.IntFunction;"]
    else:
        header = (f"public record {name}(Loadable<{base_type}> base, int minSize, int maxSize)"
                  f" implements ArrayLoadable.SizeRange<{primitive}[]> {{")
        read = lambda expr: expr
        write = lambda expr: expr
        doc = f"Loadable for a {primitive} array"
        mapper_doc = ""
        extra_import = []
    imports = sorted_imports([
        "import com.google.gson.JsonArray;",
        "import com.google.gson.JsonElement;",
        "import net.minecraft.network.RegistryFriendlyByteBuf;",
        "import slimeknights.mantle.data.loadable.Loadable;",
        "import slimeknights.mantle.data.loadable.field.DefaultingField;",
        "import slimeknights.mantle.data.loadable.field.LoadableField;",
        "import slimeknights.mantle.util.typed.TypedMap;",
        "import java.util.Arrays;",
        "import java.util.function.Function;",
    ] + extra_import)
    return f"""{HEADER}{PKG_ARRAY}
{imports}
/**
 * {doc}
 * @param base     Loadable for each element
 * @param minSize  Fewest elements, or a compact marker from {{@link ArrayLoadable}}
 * @param maxSize  Most elements{mapper_doc}
 */
{header}
  @Override
  public int getLength({primitive}[] array) {{
    return array.length;
  }}

  @Override
  public {primitive}[] convertCompact(JsonElement element, String key, TypedMap context) {{
    return new {primitive}[] {{ {read("base.convert(element, key, context)")} }};
  }}

  @Override
  public {primitive}[] convertArray(JsonArray array, String key, TypedMap context) {{
    {primitive}[] result = new {primitive}[array.size()];
    for (int i = 0; i < result.length; i++) {{
      result[i] = {read("base.convert(array.get(i), key + '[' + i + ']', context)")};
    }}
    return result;
  }}

  @Override
  public JsonElement serializeFirst({primitive}[] object) {{
    return base.serialize({write("object[0]")});
  }}

  @Override
  public void serializeAll(JsonArray array, {primitive}[] object) {{
    for ({primitive} element : object) {{
      array.add(base.serialize({write("element")}));
    }}
  }}

  @Override
  public {primitive}[] decode(RegistryFriendlyByteBuf buffer, TypedMap context) {{
    int size = buffer.readVarInt();
    {primitive}[] array = new {primitive}[size];
    for (int i = 0; i < size; i++) {{
      array[i] = {read("base.decode(buffer, context)")};
    }}
    return array;
  }}

  @Override
  public void encode(RegistryFriendlyByteBuf buffer, {primitive}[] array) {{
    buffer.writeVarInt(array.length);
    for ({primitive} element : array) {{
      base.encode(buffer, {write("element")});
    }}
  }}

  /** WHY Arrays::equals: arrays compare by identity, so the default would write equal arrays */
  @Override
  public <P> LoadableField<{primitive}[], P> defaultField(String key, {primitive}[] defaultValue, boolean serializeDefault, Function<P, {primitive}[]> getter) {{
    return new DefaultingField<>(this, key, defaultValue, serializeDefault ? null : Arrays::equals, getter);
  }}

  @Override
  public <P> LoadableField<{primitive}[], P> emptyField(String key, boolean serializeEmpty, Function<P, {primitive}[]> getter) {{
    return defaultField(key, new {primitive}[0], serializeEmpty, getter);
  }}
}}
"""


def write(path, source):
    """Write a file with LF endings, reporting changes."""
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != source:
        path.write_text(source, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")


def main():
    """Generate every file."""
    write(LOADABLE / "record/RecordLoadable.java", record_loadable())
    for count in range(1, MAX_FIELDS + 1):
        write(LOADABLE / f"record/RecordLoadable{count}.java", record_class(count, False))
    for count in range(1, MAX_FIELDS):
        write(LOADABLE / f"record/RecordWithLoader{count}.java", record_class(count, True))
    for prefix, primitive, boxed in DIRECT_ARRAYS:
        write(LOADABLE / f"array/{prefix}ArrayLoadable.java", array_class(prefix, primitive, boxed, False))
    for prefix, primitive in NARROWED_ARRAYS:
        write(LOADABLE / f"array/{prefix}ArrayLoadable.java", array_class(prefix, primitive, None, True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
